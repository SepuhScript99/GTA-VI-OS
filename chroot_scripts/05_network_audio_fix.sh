#!/bin/bash
set -Eeuo pipefail

# ============================================================================
# GTA VI OS (Vice OS) Chroot Script: Network & Audio Fix
# Resolves DNS conflicts and ensures user permissions and PipeWire services
# are configured for audio/video/network usability.
# ============================================================================

# Source the shared library from the payload directory
if [ ! -f /vice_payload/lib/common.sh ]; then
    echo "Error: /vice_payload/lib/common.sh not found." >&2
    exit 1
fi
source /vice_payload/lib/common.sh

main() {
    log_info "Configuring Network and DNS..."

    # Disable systemd-resolved to prevent conflicts with NetworkManager in Live ISO
    systemctl disable systemd-resolved.service 2>/dev/null || true

    # Ensure /etc/resolv.conf is a standard file, not a symlink to a non-existent stub
    if [ -L /etc/resolv.conf ]; then
        log_info "Removing broken resolv.conf symlink..."
        rm -f /etc/resolv.conf
    fi

    # Provide a fallback DNS (Cloudflare) so the first boot has network access
    # before NetworkManager fully initializes.
    cat <<RESOLV > /etc/resolv.conf
# Generated by Vice OS Installer
nameserver 1.1.1.1
nameserver 8.8.8.8
RESOLV
    chown root:root /etc/resolv.conf
    chmod 644 /etc/resolv.conf

    # Ensure /etc/network/interfaces only configures loopback so NetworkManager manages all NICs
    mkdir -p /etc/network/interfaces.d
    find /etc/network/interfaces.d -maxdepth 1 -type f ! -name 'lo*' -delete 2>/dev/null || true
    cat <<'INTF' > /etc/network/interfaces
# This file describes the network interfaces available on your system
# and how to activate them. For more information, see interfaces(5).

source /etc/network/interfaces.d/*

# The loopback network interface
auto lo
iface lo inet loopback
INTF
    chown root:root /etc/network/interfaces
    chmod 644 /etc/network/interfaces

    # Install all NetworkManager conf.d drop-ins (DNS + zero-config autoconnect)
    if [ -d /vice_payload/config/NetworkManager/conf.d ]; then
        mkdir -p /etc/NetworkManager/conf.d
        local nm_conf
        for nm_conf in /vice_payload/config/NetworkManager/conf.d/*.conf; do
            [ -f "$nm_conf" ] || continue
            cp "$nm_conf" /etc/NetworkManager/conf.d/
            chown root:root "/etc/NetworkManager/conf.d/$(basename "$nm_conf")"
            chmod 644 "/etc/NetworkManager/conf.d/$(basename "$nm_conf")"
        done
    fi

    # Ensure NetworkManager.conf does not block ifupdown or auto-default wired profiles
    if [ -f /etc/NetworkManager/NetworkManager.conf ]; then
        sed -i -E 's/^[[:space:]]*managed[[:space:]]*=[[:space:]]*false/managed=true/' /etc/NetworkManager/NetworkManager.conf
        sed -i -E 's/^[[:space:]]*no-auto-default[[:space:]]*=.*$/no-auto-default=/' /etc/NetworkManager/NetworkManager.conf
    fi

    # Ensure NetworkManager and essential system buses are enabled
    systemctl enable NetworkManager 2>/dev/null || true
    systemctl enable NetworkManager-dispatcher.service 2>/dev/null || true
    systemctl enable dbus 2>/dev/null || true

    log_info "Configuring User Groups and Audio..."

    # Add the vice user to necessary groups for desktop usability
    if id -u vice >/dev/null 2>&1; then
        usermod -aG netdev vice 2>/dev/null || true
        usermod -aG audio vice 2>/dev/null || true
        usermod -aG video vice 2>/dev/null || true
        if getent group pipewire >/dev/null 2>&1; then
            usermod -aG pipewire vice 2>/dev/null || true
        fi
        if getent group render >/dev/null 2>&1; then
            usermod -aG render vice 2>/dev/null || true
        fi
        if getent group plugdev >/dev/null 2>&1; then
            usermod -aG plugdev vice 2>/dev/null || true
        fi
        if getent group bluetooth >/dev/null 2>&1; then
            usermod -aG bluetooth vice 2>/dev/null || true
        fi
        if getent group lpadmin >/dev/null 2>&1; then
            usermod -aG lpadmin vice 2>/dev/null || true
        fi
        log_info "User 'vice' added to netdev, audio, video, and hardware groups."
    else
        log_warn "User 'vice' not found. Skipping group assignments."
    fi

    # Enable PipeWire / WirePlumber user services globally and RTKit daemon
    systemctl enable rtkit-daemon.service 2>/dev/null || true
    systemctl --global enable pipewire.socket pipewire-pulse.socket pipewire.service pipewire-pulse.service wireplumber.service 2>/dev/null || true

    log_success "Network and audio configuration completed."
}

main "$@"
